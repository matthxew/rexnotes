#!/usr/bin/env node
/* Generate /middleware.js (Vercel Edge Middleware) and /sitemap.xml from
 * src/data/dinosaurs.js. Re-run whenever the species set or copy changes.
 *
 *   middleware.js  — per-species OG meta + JSON-LD + noscript content,
 *                    injected into the HTML response on /d/:slug paths.
 *   sitemap.xml    — full URL list for crawlers.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://rexatlas.vercel.app';

const fakeWindow = {};
new Function('window', fs.readFileSync(path.join(ROOT, 'src/data/dinosaurs.js'), 'utf8'))(fakeWindow);
const DINOSAURS = fakeWindow.DINOSAURS;

// Compact data shape for the middleware: only the fields actually used
// in the OG meta + noscript HTML + JSON-LD body.
const meta = {};
for (const d of DINOSAURS) {
  meta[d.slug] = {
    name: d.name,
    teaser: d.teaser,
    pronunciation: d.pronunciation,
    era: d.era,
    yearsAgo: d.yearsAgo,
    diet: d.diet,
    habitat: d.habitat,
    sizeCompare: d.sizeCompare,
    forKids: d.forKids,
    forParents: d.forParents,
    trivia: d.trivia,
  };
}

const middlewareSrc = `// AUTO-GENERATED by build/middleware-gen.js — do not edit by hand.
// Per-species metadata injected into the HTML response so /d/<slug>
// URLs serve correct social-share previews and indexable content
// before any JavaScript runs.

export const config = {
  matcher: '/d/:slug',
};

const META = ${JSON.stringify(meta, null, 2)};

const esc = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/"/g, '&quot;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;');

function speciesNoscript(slug, d) {
  const trivia = d.trivia.map(t => '<li>' + esc(t) + '</li>').join('');
  return [
    '<main style="max-width:64ch;margin:48px auto;padding:0 20px;font-family:Georgia,serif;color:#1c1e25;">',
      '<p style="margin:0 0 32px;"><a href="/" style="color:#1c2a55;">← Rex\\'s Notes</a></p>',
      '<h1 style="font-size:48px;margin:0 0 12px;">' + esc(d.name) + '</h1>',
      '<p style="font-size:20px;color:#3c3d44;margin:0 0 24px;font-style:italic;">' + esc(d.teaser) + '</p>',
      '<p style="margin:0 0 8px;"><strong>Said:</strong> ' + esc(d.pronunciation) + '</p>',
      '<p style="margin:0 0 8px;"><strong>Era:</strong> ' + esc(d.era) + ' · ' + esc(d.yearsAgo) + '</p>',
      '<p style="margin:0 0 8px;"><strong>Diet:</strong> ' + esc(d.diet) + '</p>',
      '<p style="margin:0 0 8px;"><strong>Habitat:</strong> ' + esc(d.habitat) + '</p>',
      '<p style="margin:0 0 32px;"><strong>Size:</strong> ' + esc(d.sizeCompare) + '.</p>',
      '<h2 style="font-size:28px;margin:32px 0 12px;">What it was like</h2>',
      '<p style="font-size:18px;line-height:1.6;">' + esc(d.forKids) + '</p>',
      '<h2 style="font-size:28px;margin:32px 0 12px;">What we know now</h2>',
      '<p style="font-size:16px;line-height:1.6;">' + esc(d.forParents) + '</p>',
      '<h2 style="font-size:28px;margin:32px 0 12px;">Notes</h2>',
      '<ol>' + trivia + '</ol>',
    '</main>',
  ].join('');
}

function speciesJsonLd(slug, d, url, image) {
  return JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: d.name,
    name: d.name,
    description: d.teaser,
    image: image,
    url: url,
    inLanguage: 'en',
    isAccessibleForFree: true,
    isPartOf: {
      '@type': 'WebSite',
      name: "Rex's Notes",
      url: '${SITE}',
    },
    about: {
      '@type': 'Thing',
      name: d.name,
      description: d.forParents,
    },
    publisher: {
      '@type': 'Organization',
      name: "Rex's Notes",
      url: '${SITE}',
    },
  });
}

export default async function middleware(request) {
  const url = new URL(request.url);
  const m = url.pathname.match(/^\\/d\\/([^\\/]+)/);
  if (!m) return;

  const slug = m[1];
  const data = META[slug];
  if (!data) return; // unknown slug — pass through to default

  const upstream = await fetch(new URL('/', url));
  if (!upstream.ok) return;
  let html = await upstream.text();

  const title = data.name + " — Rex's Notes";
  const desc = data.teaser;
  const ogUrl = url.origin + url.pathname;
  const ogImage = url.origin + '/og/' + slug + '.png';

  const replacements = [
    [/<title>[\\s\\S]*?<\\/title>/, '<title>' + esc(title) + '</title>'],
    [/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + esc(desc) + '">'],
    [/<link rel="canonical" href="[^"]*">/, '<link rel="canonical" href="' + ogUrl + '">'],
    [/<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="' + esc(title) + '">'],
    [/<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="' + esc(desc) + '">'],
    [/<meta property="og:url" content="[^"]*">/, '<meta property="og:url" content="' + ogUrl + '">'],
    [/<meta property="og:image" content="[^"]*">/, '<meta property="og:image" content="' + ogImage + '">'],
    [/<meta property="og:image:alt" content="[^"]*">/, '<meta property="og:image:alt" content="' + esc(data.name) + ' — illustration on cream paper.">'],
    [/<meta name="twitter:title" content="[^"]*">/, '<meta name="twitter:title" content="' + esc(title) + '">'],
    [/<meta name="twitter:description" content="[^"]*">/, '<meta name="twitter:description" content="' + esc(desc) + '">'],
    [/<meta name="twitter:image" content="[^"]*">/, '<meta name="twitter:image" content="' + ogImage + '">'],
    // Replace the home noscript fallback with this species' content.
    [/<noscript>[\\s\\S]*?<\\/noscript>/, '<noscript>' + speciesNoscript(slug, data) + '</noscript>'],
  ];
  for (const [re, val] of replacements) html = html.replace(re, val);

  // Inject JSON-LD before </head> for rich search results.
  const ldTag = '<script type="application/ld+json">' + speciesJsonLd(slug, data, ogUrl, ogImage) + '</script>';
  html = html.replace(/<\\/head>/, ldTag + '</head>');

  return new Response(html, {
    status: 200,
    headers: {
      'content-type': 'text/html; charset=utf-8',
      'cache-control': 'public, max-age=300, s-maxage=86400',
    },
  });
}
`;

fs.writeFileSync(path.join(ROOT, 'middleware.js'), middlewareSrc);
console.log('wrote middleware.js (' + Object.keys(meta).length + ' species)');

// Regenerate the species list in shell.html's home <noscript> block. This
// keeps the crawler-visible content in sync with the dataset without
// requiring a manual edit each time a species is added.
const shellPath = path.join(ROOT, 'build/shell.html');
const escHtml = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/"/g, '&quot;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;');
const speciesItems = DINOSAURS.map(d =>
  '          <li><a href="/d/' + d.slug + '" style="color:#1c2a55;">' + escHtml(d.name) + '</a> — ' + escHtml(d.teaser) + '</li>'
).join('\n');
let shell = fs.readFileSync(shellPath, 'utf8');
shell = shell.replace(
  /(<ul style="list-style:none;padding:0;font-size:18px;line-height:1\.7;">)[\s\S]*?(<\/ul>)/,
  '$1\n' + speciesItems + '\n        $2'
);
fs.writeFileSync(shellPath, shell);
console.log('updated build/shell.html home noscript (' + DINOSAURS.length + ' species)');

// sitemap.xml — home + section pages + every species detail page.
const urls = [
  SITE + '/',
  SITE + '/about',
  SITE + '/timeline',
  SITE + '/map',
  ...DINOSAURS.map(d => SITE + '/d/' + d.slug),
];
const lastmod = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${u}</loc><lastmod>${lastmod}</lastmod></url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap);
console.log('wrote sitemap.xml (' + urls.length + ' urls)');
