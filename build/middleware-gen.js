#!/usr/bin/env node
/* Generate /middleware.js (Vercel Edge Middleware) with the per-species
 * metadata inlined. Run this whenever the species set or copy changes. */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const fakeWindow = {};
new Function('window', fs.readFileSync(path.join(ROOT, 'src/data/dinosaurs.js'), 'utf8'))(fakeWindow);

const meta = {};
for (const d of fakeWindow.DINOSAURS) {
  meta[d.slug] = { name: d.name, teaser: d.teaser };
}

const out = `// AUTO-GENERATED by build/middleware-gen.js — do not edit by hand.
// Per-species OG/Twitter metadata for the bundled HTML response, so
// /d/<slug> URLs render with the correct social-share preview before
// any JavaScript runs.

export const config = {
  // Run on /d/:slug only. Everything else (/, /timeline, /map, /about,
  // static files) bypasses middleware and gets the default response.
  matcher: '/d/:slug',
};

const META = ${JSON.stringify(meta, null, 2)};

const esc = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/"/g, '&quot;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;');

export default async function middleware(request) {
  const url = new URL(request.url);
  const m = url.pathname.match(/^\\/d\\/([^\\/]+)/);
  if (!m) return;

  const slug = m[1];
  const data = META[slug];
  if (!data) return; // unknown slug — fall through to the SPA, default OG

  // Fetch the bundled index.html. The matcher means this fetch (to /)
  // doesn't re-trigger middleware, no infinite loop.
  const upstream = await fetch(new URL('/', url));
  if (!upstream.ok) return;

  let html = await upstream.text();

  const title = \`\${data.name} — Rex's Notes\`;
  const desc = data.teaser;
  const ogUrl = url.origin + url.pathname;
  const ogImage = \`\${url.origin}/og/\${slug}.png\`;

  // Replace meta tags. Match the exact opening attribute so we only
  // touch the tags shell.html emits, not anything inside the bundle.
  const replacements = [
    [/<title>[\\s\\S]*?<\\/title>/, \`<title>\${esc(title)}</title>\`],
    [/<meta name="description" content="[^"]*">/, \`<meta name="description" content="\${esc(desc)}">\`],
    [/<link rel="canonical" href="[^"]*">/, \`<link rel="canonical" href="\${ogUrl}">\`],
    [/<meta property="og:title" content="[^"]*">/, \`<meta property="og:title" content="\${esc(title)}">\`],
    [/<meta property="og:description" content="[^"]*">/, \`<meta property="og:description" content="\${esc(desc)}">\`],
    [/<meta property="og:url" content="[^"]*">/, \`<meta property="og:url" content="\${ogUrl}">\`],
    [/<meta property="og:image" content="[^"]*">/, \`<meta property="og:image" content="\${ogImage}">\`],
    [/<meta property="og:image:alt" content="[^"]*">/, \`<meta property="og:image:alt" content="\${esc(data.name)} — illustration on cream paper.">\`],
    [/<meta name="twitter:title" content="[^"]*">/, \`<meta name="twitter:title" content="\${esc(title)}">\`],
    [/<meta name="twitter:description" content="[^"]*">/, \`<meta name="twitter:description" content="\${esc(desc)}">\`],
    [/<meta name="twitter:image" content="[^"]*">/, \`<meta name="twitter:image" content="\${ogImage}">\`],
  ];
  for (const [re, val] of replacements) html = html.replace(re, val);

  return new Response(html, {
    status: 200,
    headers: {
      'content-type': 'text/html; charset=utf-8',
      'cache-control': 'public, max-age=300, s-maxage=86400',
    },
  });
}
`;

fs.writeFileSync(path.join(ROOT, 'middleware.js'), out);
console.log('wrote middleware.js (' + Object.keys(meta).length + ' species)');
